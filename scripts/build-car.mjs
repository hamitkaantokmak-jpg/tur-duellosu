import fs from "node:fs/promises";
import * as T from "three";
import { GLTFExporter } from "three/addons/exporters/GLTFExporter.js";
import { mergeGeometries } from "three/addons/utils/BufferGeometryUtils.js";
import { NodeIO } from "@gltf-transform/core";
import { ALL_EXTENSIONS } from "@gltf-transform/extensions";
import { dedup, weld, meshopt } from "@gltf-transform/functions";
import { MeshoptEncoder, MeshoptDecoder } from "meshoptimizer";
// FileReader is needed by the browser-oriented exporter even for texture-free GLBs.
globalThis.FileReader = class {
  readAsArrayBuffer(blob) {
    blob.arrayBuffer().then((v) => {
      this.result = v;
      this.onloadend?.();
    });
  }
  readAsDataURL(blob) {
    blob.arrayBuffer().then((v) => {
      this.result =
        "data:application/octet-stream;base64," +
        Buffer.from(v).toString("base64");
      this.onloadend?.();
    });
  }
};
import {makeCar as model} from "./car-v3.mjs";
await MeshoptEncoder.ready;
await MeshoptDecoder.ready;
await fs.mkdir("assets/cars", { recursive: true });
const io = new NodeIO()
  .registerExtensions(ALL_EXTENSIONS)
  .registerDependencies({
    "meshopt.encoder": MeshoptEncoder,
    "meshopt.decoder": MeshoptDecoder,
  });
const stats = [];
for (const [name, detail] of [
  ["low", 1],
  ["medium", 2],
  ["high", 4],
]) {
  const root = model(detail);
  root.updateMatrixWorld(true);
  const raw = await new GLTFExporter().parseAsync(root, {
    binary: true,
    onlyVisible: true,
  });
  const doc = await io.readBinary(new Uint8Array(raw));
  await doc.transform(
    dedup(),
    weld(),
    meshopt({ encoder: MeshoptEncoder, level: "medium" }),
  );
  const bytes = await io.writeBinary(doc);
  await fs.writeFile("assets/cars/open-wheel-" + name + ".glb", bytes);
  let triangles = 0;
  root.traverse((o) => {
    if (o.geometry)
      triangles +=
        (o.geometry.index?.count || o.geometry.attributes.position.count) / 3;
  });
  stats.push({ lod: name, triangles, bytes: bytes.length });
}
await fs.writeFile(
  "assets/cars/manifest.json",
  JSON.stringify(
    {
      name: "Tur Düellosu V3 Open Wheel",
      origin:
        "Original V3 ground-effect design generated by scripts/car-v3.mjs; 2.01m width, 3.60m wheelbase, rounded tyres and sculpted body. No team logos or official vehicle reproduction",
      units: "metres",
      forward: "+Z",
      compression: "EXT_meshopt_compression",
      levels: stats,
    },
    null,
    2,
  ) + "\n",
);
console.log(stats);
